#!/usr/bin/env bash
# Full training pipeline on the complete dataset, then a serving config for the new model.
#
#   export EMBER2024_DIR=/data/ember2024
#   scripts/train_all.sh [configs/win64.yaml]
#
# Writes configs/serving.<arch>.yaml. Output of every step goes to work/train_all-<time>.log.
set -euo pipefail

CONFIG=${1:-configs/win64.yaml}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
SILKSCAN=".venv/bin/silkscan"
ARCH=$(uname -m)
mkdir -p work
LOG="work/train_all-$(date +%Y%m%d-%H%M%S).log"
: "${EMBER2024_DIR:?set EMBER2024_DIR to the extracted EMBER2024 directory}"

step() { echo "[$(date +%H:%M:%S)] $1"; shift; "$@" >> "$LOG" 2>&1; }

step "manifest"  $SILKSCAN manifest -c "$CONFIG" --force
step "features"  $SILKSCAN features -c "$CONFIG"
step "train"     $SILKSCAN train -c "$CONFIG"
RUN=$(grep -o '"run_dir": "[^"]*"' "$LOG" | tail -1 | cut -d'"' -f4)
echo "run: $RUN"
step "file-kind thresholds" $SILKSCAN threshold --run "$RUN" --policy auto -c "$CONFIG"
step "review zone"          $SILKSCAN threshold --run "$RUN" --review-fpr 0.01 -c "$CONFIG"
step "threat type"          $SILKSCAN train-type --run "$RUN" -c "$CONFIG"
STAGE2=$(ls -d "$RUN"/stage2/*/ | tail -1)
WORK_DIR=$(.venv/bin/python -c "from silkscan.config import load_config as l; print(l('$CONFIG').work_dir)")
HASHES="$WORK_DIR/hashes/known_malicious.npy"
step "known-hash list"      $SILKSCAN hashlist -c "$CONFIG" --splits train validation --out "$HASHES"

BACKEND=lightgbm
if grep -qw nnpa /proc/cpuinfo 2>/dev/null && .venv/bin/python -c "import snapml" 2>/dev/null; then
    if step "snapml-nnpa threshold" $SILKSCAN threshold --run "$RUN" --backend snapml-nnpa -c "$CONFIG"; then
        BACKEND=snapml-nnpa
    fi
fi
step "evaluate"             $SILKSCAN --log-level WARNING evaluate --run "$RUN" --backend "$BACKEND" -c "$CONFIG"

SERVING="configs/serving.$ARCH.yaml"
cat > "$SERVING" <<EOF
# Generated by scripts/train_all.sh
run: $RUN
stage2: ${STAGE2%/}
backend: $BACKEND
explain_top: 0
max_file_mb: 100
short_circuit: true
checks:
  - name: pe_format
    params: {allowed_machines: [AMD64]}
  - name: hash_list
    params: {deny: [rules/hashes/deny.txt, $HASHES], allow: rules/hashes/allow.txt}
  - name: yara
    required: false
    params: {rules_dir: rules/yara, timeout_s: 5, default_severity: medium, allow_force: false}
EOF
echo "serving config: $SERVING (backend $BACKEND)"
echo "report: $SILKSCAN report --run $RUN    log: $LOG"
